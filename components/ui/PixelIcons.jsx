export function PixelSeasonIcon({ season = 'Spring', size = 16, className = '', style = {} }) {
  const s = (season || '').toLowerCase();
  if (s.includes('spring')) return <PixelSpringFlower size={size} className={className} style={style} />;
  if (s.includes('summer')) return <PixelSummerSun size={size} className={className} style={style} />;
  if (s.includes('fall') || s.includes('autumn')) return <PixelAutumnLeaf size={size} className={className} style={style} />;
  return <PixelWinterSnowflake size={size} className={className} style={style} />;
}

export function PixelWeatherIcon({ weather = 'clear', size = 16, className = '', style = {} }) {
  const w = (weather || '').toLowerCase();
  if (w.includes('rain')) return <PixelRain size={size} className={className} style={style} />;
  if (w.includes('snow')) return <PixelWinterSnowflake size={size} className={className} style={style} />;
  return <PixelSummerSun size={size} className={className} style={style} />;
}

export function PixelHotbarIcon({ id = null, size = 22, className = '', style = {} }) {
  switch (id) {
    case 'todos': return <PixelWheat size={size} className={className} style={style} />;
    case 'reminders': return <PixelBell size={size} className={className} style={style} />;
    case 'debts': return <PixelCoin size={size} className={className} style={style} />;
    case 'deadlines': return <PixelNoticeBoard size={size} className={className} style={style} />;
    case 'dates': return <PixelWindmill size={size} className={className} style={style} />;
    case 'watchlist': return <PixelCinema size={size} className={className} style={style} />;
    case 'audit': return <PixelScroll size={size} className={className} style={style} />;
    case 'settings': return <PixelHammer size={size} className={className} style={style} />;
    default: return <PixelMap size={size} className={className} style={style} />;
  }
}
